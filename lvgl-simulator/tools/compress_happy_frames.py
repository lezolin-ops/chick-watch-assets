#!/usr/bin/env python3
"""Shrink the 6 AI happy keyframes for firmware.

Reads the baked 192x192 ARGB8888 descriptors out of src/pet_happy_frames.c and
emits src/pet_happy_kf.c with two lossless-or-near-lossless savings stacked:

  1. crop   - union alpha bounding box, shared across all 6 frames so the poses
              stay aligned. Pure lossless; the caller re-adds the offset.
  2. RGB565A8 - LVGL native 3 bytes/px (RGB565 plane followed by an A8 plane),
              supported by the software renderer (LV_DRAW_SW_SUPPORT_RGB565A8).

Why not a palette: the AI art has real gradients + antialiasing (~11k unique
RGBA colours), so L8 would band badly.

Not attempted (bigger win, needs a custom decoder): RLE on top of the crop
would land around 276 KB instead of 338 KB.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src' / 'pet_happy_frames.c'
OUT = ROOT / 'src' / 'pet_happy_kf.c'
# Reference geometry: the daily idle sprite the keyframes have to cut against.
# Without this the AI art is ~12% smaller and floats 9px above the ground, so
# every cut between the two reads as a shrink-and-lift jump.
REFF = ROOT / 'src' / 'pet_chick_192.c'
REFSYM = 'pet_chick_192'
W = H = 192
NFRAMES = 6


def read_map(path: Path, sym: str) -> np.ndarray:
    t = path.read_text(encoding='utf-8', errors='ignore')
    m = re.search(rf'{sym}_map\[\] = \{{(.*?)\}};', t, re.S)
    if not m:
        sys.exit(f'{sym}_map not found in {path}')
    vals = bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(1)))
    if len(vals) != W * H * 4:
        sys.exit(f'{sym}: {len(vals)} bytes, expected {W * H * 4}')
    # LVGL ARGB8888 is stored little-endian: B, G, R, A
    return np.frombuffer(vals, dtype=np.uint8).reshape(H, W, 4)


def load(idx: int) -> np.ndarray:
    return read_map(SRC, f'pet_happy_{idx}')


frames = [load(i) for i in range(NFRAMES)]
alpha = np.stack([f[:, :, 3] for f in frames])

# reference (idle) bounding box -> target size and ground line
ref = read_map(REFF, REFSYM)
rys, rxs = np.where(ref[:, :, 3] > 8)
ref_x0, ref_x1 = int(rxs.min()), int(rxs.max())
ref_y0, ref_y1 = int(rys.min()), int(rys.max())
ref_h = ref_y1 - ref_y0 + 1
ref_cx = (ref_x0 + ref_x1) / 2

ys, xs = np.where(alpha.max(axis=0) > 8)
x0, y0 = int(xs.min()), int(ys.min())
x1, y1 = int(xs.max()), int(ys.max())
ai_w = x1 - x0 + 1
ai_h = y1 - y0 + 1
# one shared scale for every frame, otherwise the sprite breathes between poses
scale = ref_h / ai_h
# pad to even so the RGB565 row stride is 2-byte friendly
cw = (round(ai_w * scale) + 1) & ~1
ch = (ref_h + 1) & ~1
px0 = int(round(ref_cx - cw / 2))
py0 = ref_y0

orig_bytes = W * H * 4 * NFRAMES
crop_bytes = cw * ch * 4 * NFRAMES
out_bytes = cw * ch * 3 * NFRAMES


def to_rgb565a8(f: np.ndarray) -> bytes:
    from PIL import Image
    sub = f[y0:y1 + 1, x0:x1 + 1]
    img = Image.fromarray(sub, 'RGBA').resize((cw, ch), Image.LANCZOS)
    sub = np.asarray(img)
    b = sub[:, :, 0].astype(np.uint16)
    g = sub[:, :, 1].astype(np.uint16)
    r = sub[:, :, 2].astype(np.uint16)
    a = sub[:, :, 3]
    rgb = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    rgb = rgb.astype('<u2')  # little-endian uint16
    return rgb.tobytes() + a.tobytes()


def c_array(name: str, data: bytes, per_line: int = 16) -> str:
    lines = [f'static const uint8_t {name}[] = {{']
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append('    ' + ' '.join(f'0x{v:02X},' for v in chunk))
    if lines[-1].endswith(','):
        lines[-1] = lines[-1][:-1]
    lines.append('};')
    return '\n'.join(lines)


parts = [
    '/* Auto-generated: cropped + RGB565A8 AI happy keyframes for firmware.',
    ' * Generated by tools/compress_happy_frames.py -- do not edit by hand.',
    ' *',
    f' * Source : 192x192 ARGB8888 x{NFRAMES}  ({orig_bytes / 1024:.1f} KB)',
    f' * Aligned: AI bbox {ai_w}x{ai_h} scaled x{scale:.3f} to match the daily '
    f'idle sprite ({ref_h}px tall, ground y={ref_y1}, centre x={ref_cx:g})',
    f' * Crop   : offset ({px0},{py0}) size {cw}x{ch}  '
    f'-> ARGB8888 would be {crop_bytes / 1024:.1f} KB',
    f' * Output : RGB565 + A8 planes  -> {out_bytes / 1024:.1f} KB '
    f'(-{(1 - out_bytes / orig_bytes) * 100:.1f}%)',
    ' *',
    ' * The placement is HAPPY_KF_X / HAPPY_KF_Y: the caller must draw this',
    ' * image at that offset inside the 192x192 character box. Do not rescale it',
    ' * at runtime -- the scale is already baked in so it cuts against the idle',
    ' * sprite without a size or ground-line jump.',
    ' */',
    '#include "lvgl/lvgl.h"',
    '',
    f'#define HAPPY_KF_W {cw}',
    f'#define HAPPY_KF_H {ch}',
    f'#define HAPPY_KF_X {px0}',
    f'#define HAPPY_KF_Y {py0}',
    '',
]

for i in range(NFRAMES):
    data = to_rgb565a8(frames[i])
    assert len(data) == cw * ch * 3, (i, len(data))
    parts.append(c_array(f'pet_happy_kf_{i}_map', data))
    parts.append(f'const lv_image_dsc_t pet_happy_kf_{i} = {{')
    parts.append('    .header = {')
    parts.append(f'        .cf = LV_COLOR_FORMAT_RGB565A8,')
    parts.append('        .w = HAPPY_KF_W,')
    parts.append('        .h = HAPPY_KF_H,')
    parts.append(f'        .stride = HAPPY_KF_W * 2,')
    parts.append('    },')
    parts.append(f'    .data_size = sizeof(pet_happy_kf_{i}_map),')
    parts.append(f'    .data = pet_happy_kf_{i}_map,')
    parts.append('};')
    parts.append('')

OUT.write_text('\n'.join(parts), encoding='utf-8')

print(f'reference    : idle sprite bbox x {ref_x0}..{ref_x1} y {ref_y0}..{ref_y1} '
      f'({ref_x1 - ref_x0 + 1}x{ref_h}), ground y={ref_y1}, centre x={ref_cx:g}')
print(f'AI bbox      : x {x0}..{x1}  y {y0}..{y1}  ({ai_w}x{ai_h})')
print(f'aligned      : scale x{scale:.3f} -> crop {cw}x{ch} at ({px0},{py0})'
      f'   (ground y={py0 + ch - 1})')
print(f'raw  ARGB8888 192x192 x{NFRAMES} : {orig_bytes / 1024:8.1f} KB')
print(f'crop ARGB8888 {cw}x{ch} x{NFRAMES}     : {crop_bytes / 1024:8.1f} KB  '
      f'(-{(1 - crop_bytes / orig_bytes) * 100:.1f}%, lossless)')
print(f'crop RGB565A8 {cw}x{ch} x{NFRAMES}     : {out_bytes / 1024:8.1f} KB  '
      f'(-{(1 - out_bytes / orig_bytes) * 100:.1f}%)  <-- written')
print(f'C source written: {OUT}  ({OUT.stat().st_size / 1024:.1f} KB of text)')
